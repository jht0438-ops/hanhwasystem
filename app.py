def fmt(v, digits=0):
    if pd.isna(v): return "-"
    return f"{v:,.{digits}f}"

def explain_tab(why, how, conclusion):
    st.markdown("### 왜 분석하나요?")
    st.write(why)
    st.markdown("### 어떻게 분석하나요?")
    st.write(how)
    st.markdown("### 이 탭에서 얻을 수 있는 결론은 무엇인가요?")
    st.markdown(f'<div class="insight">{conclusion}</div>', unsafe_allow_html=True)
    st.divider()

def risk_label(row):
    score = 0
    reasons = []
    if row["진행률"] >= 90 and row["매출채권_억원"] >= 50:
        score += 2; reasons.append("높은 진행률 대비 채권 잔액")
    if row["계약자산_억원"] >= 500:
        score += 2; reasons.append("계약자산 규모 큼")
    elif row["계약자산_억원"] >= 100:
        score += 1; reasons.append("계약자산 모니터링 필요")
    if score >= 3: level="집중관리"
    elif score >= 1: level="모니터링"
    else: level="양호"
    return pd.Series([level, ", ".join(reasons) if reasons else "특이 신호 없음"])

